function shift(
  id: string,
  profileId: string,
  templateId: string,
  status: AttendanceShift["status"],
  dateLocal: string,
  plannedStartAt: string,
  plannedEndAt: string,
  extra: Partial<AttendanceShift> = {},
): AttendanceShift {
  const operator = operatorsById.get(profileId);
  const template = attendanceTemplates.find((candidate) => candidate.id === templateId);

  if (!operator) {
    throw new Error(`Unknown mock operator: ${profileId}`);
  }

  return {
    id,
    profileId,
    operatorName: operator.name,
    operatorExtension: operator.extension,
    templateId,
    templateLabel: template?.label,
    status,
    dateLocal,
    timezone: "Europe/Bratislava",
    plannedStartAt,
    plannedEndAt,
    ...extra,
  };
}
